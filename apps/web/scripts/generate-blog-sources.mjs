import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const webRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contentDir = path.join(webRoot, "content", "blog");
const outFile = path.join(webRoot, "src", "lib", "blog", "sources.generated.ts");

const names = fs.existsSync(contentDir)
  ? fs
      .readdirSync(contentDir)
      .filter((name) => name.endsWith(".md") || name.endsWith(".mdx"))
      .sort()
  : [];

const entries = names.map((name) => {
  const raw = fs.readFileSync(path.join(contentDir, name), "utf8");
  return `  ${JSON.stringify(name)}: ${JSON.stringify(raw)},`;
});

const source = `// Generated by scripts/generate-blog-sources.mjs. Do not edit.
// Production (the Cloudflare Worker) reads this module. The worker re-renders
// blog routes on every request and has no content/blog directory.

export const blogSources: Record<string, string> = {
${entries.join("\n")}
};
`;

const previous = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8") : "";
if (previous !== source) {
  fs.writeFileSync(outFile, source);
}
